"use strict";

/**
 * The generated id declarations. They only ever contain ids and kinds - no hashes, sizes or
 * paths - so the file is identical on every machine and a diff in review is exactly "these ids
 * were added/removed". It augments the lib's empty `AssetRegistry`, so the lib's typed accessors
 * (`SpriteId`, `SoundId` ...) become checked without lib knowing the game.
 *
 * The top-level `export {}` is required: without it TypeScript reads the file as an ambient
 * module declaration that *replaces* the lib's module instead of augmenting it.
 */

const { CompareKeys } = require("./ids");

const HEADER = [
    "// <auto-generated> by logic-incubator/packages/lib/scripts/build-assets.js. Do not edit.",
    "// Regenerate: npm run assets    Verify: npm run assets:check"
];

/**
 * @param {{ name: string, assets: { id: string, kind: string }[] }[]} bundles every bundle, dev-only ones included
 * @param {string} moduleName the module whose registries are augmented
 */
function GenerateDts(bundles, moduleName) {
    const names = bundles.map(b => b.name).sort(CompareKeys);
    const entries = [];
    bundles.forEach(b => b.assets.forEach(a => entries.push([a.id, a.kind])));
    entries.sort((a, b) => CompareKeys(a[0], b[0]));

    const block = (title, rows) => rows.length
        ? [`    interface ${title} {`, ...rows.map(row => `        ${row}`), "    }"]
        : [`    interface ${title} {}`];

    return [
        ...HEADER,
        "export {};",
        "",
        `declare module ${JSON.stringify(moduleName)} {`,
        ...block("BundleRegistry", names.map(n => `${JSON.stringify(n)}: true;`)),
        ...block("AssetRegistry", entries.map(([id, kind]) => `${JSON.stringify(id)}: ${JSON.stringify(kind)};`)),
        "}",
        ""
    ].join("\n");
}

/** Whether `existing` (as read from disk, any line endings) differs from `generated`. */
function IsDtsStale(existing, generated) {
    return existing === undefined || existing.replace(/\r\n/g, "\n") !== generated;
}

module.exports = { GenerateDts, IsDtsStale };
