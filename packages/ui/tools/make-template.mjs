// Builds the Aseprite template for the UI art: every frame of the atlas laid out on one sheet on an 8-pixel grid (seeded with the art as it is now), with
//   art/ui-template.png        the sheet, transparent between the pieces
//   art/ui-template.lua        an Aseprite script that adds one named slice per piece (nine-patch centres included) and saves the sprite as art/ui.aseprite
//   art/ui-template-guide.png  the sheet at 3x with each piece numbered, and a legend of numbers, names, sizes and insets
//   art/ui-template.slices.json  the slices as Aseprite's own export (--list-slices) writes them, so the slicer can be tried without Aseprite
//   art/README.md              how to use them
// Draw inside the slices in Aseprite, then `slice-sheet.mjs` turns the sprite back into the atlas's frames. Run this once to start; running it again rewrites the template
// from the atlas as it is, so it never touches art/ui.aseprite (which holds the edits).
//
//   node packages/ui/tools/make-template.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LoadFont, DrawText } from "./lib/bmfont.mjs";
import { ReadFrames } from "./lib/frames.mjs";
import { Composite, CreateImage, UpscaleNearest } from "./lib/image.mjs";
import { CompareNames, LayoutPieces } from "./lib/layout.mjs";

const require = createRequire(import.meta.url);
const { PNG } = require("pngjs");
const here = dirname(fileURLToPath(import.meta.url));
const uiDir = join(here, "..");
const artDir = join(uiDir, "art");
const SHEET_WIDTH = 512;
const GUIDE_SCALE = 3;

const GROUPS = [
    { title: "BUTTONS", match: /^btn_/, colour: [106, 96, 196] },
    { title: "PANELS AND FRAMES", match: /^(panel_|window_|tooltip|dialogue|toast_|portrait_)/, colour: [96, 160, 196] },
    { title: "BORDERS AND DIVIDERS", match: /^border_/, colour: [160, 106, 196] },
    { title: "BARS", match: /^bar_/, colour: [196, 96, 96] },
    { title: "CHECKBOXES AND RADIOS", match: /^(checkbox_|radio_)/, colour: [96, 196, 128] },
    { title: "SLIDERS AND SCROLLBARS", match: /^(slider_|scroll_)/, colour: [196, 176, 96] },
    { title: "TABS", match: /^tab_/, colour: [96, 196, 196] },
    { title: "TEXT FIELDS", match: /^field_/, colour: [196, 128, 96] },
    { title: "INVENTORY SLOTS", match: /^slot_/, colour: [128, 196, 96] },
    { title: "ICONS", match: /^icon_/, colour: [196, 96, 176] }
];

const read = file => {
    const png = PNG.sync.read(readFileSync(file));
    return { width: png.width, height: png.height, data: new Uint8Array(png.data) };
};
const write = (file, img) => writeFileSync(file, PNG.sync.write({ width: img.width, height: img.height, data: Buffer.from(img.data) }));

const spritesDir = join(uiDir, "assets/ui/sprites/ui");
const frames = ReadFrames(join(uiDir, "assets/ui/data/frames.json"));
const names = readdirSync(spritesDir).filter(f => f.endsWith(".png")).map(f => f.slice(0, -4));
const images = new Map(names.map(name => [name, read(join(spritesDir, name + ".png"))]));

const groups = GROUPS.map(g => ({ ...g, pieces: names.filter(n => g.match.test(n)).sort(CompareNames).map(name => ({ name, width: images.get(name).width, height: images.get(name).height })) }));
const unplaced = names.filter(n => !GROUPS.some(g => g.match.test(n)));
if (unplaced.length) {
    groups.push({ title: "OTHER", match: /$^/, colour: [160, 160, 160], pieces: unplaced.sort(CompareNames).map(name => ({ name, width: images.get(name).width, height: images.get(name).height })) });
}
const { placed, headings, height } = LayoutPieces(groups, SHEET_WIDTH);
const colourOf = title => (groups.find(g => g.title === title) || { colour: [160, 160, 160] }).colour;
const centreOf = name => {
    const insets = frames[name] && frames[name].insets;
    const img = images.get(name);
    return insets ? { x: insets.left, y: insets.top, w: img.width - insets.left - insets.right, h: img.height - insets.top - insets.bottom } : null;
};

// ---- the sheet ---------------------------------------------------------------------------------------------------------
mkdirSync(artDir, { recursive: true });
const sheet = CreateImage(SHEET_WIDTH, height);
placed.forEach(p => Composite(sheet, images.get(p.name), p.x, p.y));
write(join(artDir, "ui-template.png"), sheet);

// ---- the Aseprite script -------------------------------------------------------------------------------------------------
const slash = p => resolve(p).replace(/\\/g, "/");
const rows = placed.map(p => {
    const c = centreOf(p.name);
    const col = colourOf(p.group);
    return `  { "${p.name}", ${p.x}, ${p.y}, ${p.width}, ${p.height}, ${c ? [c.x, c.y, c.w, c.h].join(", ") : "nil, nil, nil, nil"}, ${col.join(", ")} },`;
});
const lua = `-- Generated by packages/ui/tools/make-template.mjs - run it in Aseprite (File > Scripts) to add the template's slices.
-- Each slice is one frame of the game's UI atlas, named as the skin names it; a slice with a nine-patch centre is a frame that stretches (its centre is the part that grows).
local TEMPLATE = "${slash(join(artDir, "ui-template.png"))}"
local TARGET = "${slash(join(artDir, "ui.aseprite"))}"
local WIDTH, HEIGHT = ${SHEET_WIDTH}, ${height}
-- name, x, y, width, height, centre x, y, width, height (or nil), then the slice's display colour
local SLICES = {
${rows.join("\n")}
}

local sprite = app.activeSprite
if sprite == nil or sprite.width ~= WIDTH or sprite.height ~= HEIGHT then
  sprite = Sprite{ fromFile = TEMPLATE, oneFrame = true }
end
if #sprite.slices > 0 then
  app.alert("This sprite already has slices, so nothing was added. Open ui-template.png afresh to start over.")
  return
end

app.transaction(function()
  for _, s in ipairs(SLICES) do
    local slice = sprite:newSlice(Rectangle(s[2], s[3], s[4], s[5]))
    slice.name = s[1]
    if s[6] ~= nil then
      slice.center = Rectangle(s[6], s[7], s[8], s[9])
    end
    slice.color = Color{ r = s[10], g = s[11], b = s[12], a = 255 }
  end
end)

local saved = ""
if app.fs.isFile(TARGET) then
  saved = "\\n" .. TARGET .. " already exists, so the sprite was not saved over it (File > Save As to keep this one)."
else
  sprite:saveAs(TARGET)
  saved = "\\nSaved as " .. TARGET
end
app.alert("Added " .. #SLICES .. " slices." .. saved)
`;
writeFileSync(join(artDir, "ui-template.lua"), lua);
writeFileSync(
    join(artDir, "ui-template.slices.json"),
    JSON.stringify(
        {
            frames: [],
            meta: {
                app: "make-template.mjs (shaped like Aseprite's export)",
                image: "ui-template.png",
                size: { w: SHEET_WIDTH, h: height },
                slices: placed.map(p => {
                    const c = centreOf(p.name);
                    return { name: p.name, color: "#0000ffff", keys: [{ frame: 0, bounds: { x: p.x, y: p.y, w: p.width, h: p.height }, ...(c ? { center: c } : {}) }] };
                })
            }
        },
        null,
        "\t"
    ) + "\n"
);

// ---- the guide -----------------------------------------------------------------------------------------------------------
const font = LoadFont(join(uiDir, "assets/ui/fonts/wonky_small.fnt"));
const LEGEND_COLUMN = SHEET_WIDTH * GUIDE_SCALE;
const legendLines = placed.length;
const legendRows = Math.ceil(legendLines / 3);
const guide = CreateImage(SHEET_WIDTH * GUIDE_SCALE, height * GUIDE_SCALE + legendRows * font.lineHeight + 40, [18, 20, 34, 255]);
for (let y = 0; y < height * GUIDE_SCALE; y++) {
    for (let x = 0; x < guide.width; x++) {
        const c = (((x / (8 * GUIDE_SCALE)) | 0) + ((y / (8 * GUIDE_SCALE)) | 0)) & 1 ? 30 : 36;
        guide.data.set([c, c, c + 10, 255], (y * guide.width + x) * 4);
    }
}
headings.forEach(h => DrawText(guide, font, h.title, h.x * GUIDE_SCALE, h.y * GUIDE_SCALE, colourOf(h.title)));
placed.forEach((p, i) => {
    Composite(guide, UpscaleNearest(images.get(p.name), GUIDE_SCALE), p.x * GUIDE_SCALE, p.y * GUIDE_SCALE);
    DrawText(guide, font, String(i + 1), p.x * GUIDE_SCALE, p.y * GUIDE_SCALE - font.lineHeight - 2, [255, 220, 80]);
});
placed.forEach((p, i) => {
    const insets = frames[p.name] && frames[p.name].insets;
    const text = `${i + 1} ${p.name}  ${p.width}x${p.height}${insets ? "  9: " + [insets.left, insets.top, insets.right, insets.bottom].join(",") : ""}`;
    DrawText(guide, font, text, (i % 3) * (LEGEND_COLUMN / 3) + 12, height * GUIDE_SCALE + 20 + Math.floor(i / 3) * font.lineHeight, [210, 210, 235]);
});
write(join(artDir, "ui-template-guide.png"), guide);

writeFileSync(join(artDir, "README.md"), `# UI art in Aseprite

The UI atlas as one Aseprite sprite: every frame is a *slice* named as the skin names it (\`btn_primary_normal\`...), on an 8-pixel grid. Draw in the slices, slice the sprite back
into the game's atlas with one command. One pixel here is one UI pixel (the UI is drawn at 2x).

1. **Start** (once). Open \`ui-template.png\` in Aseprite, then run \`ui-template.lua\` (File > Scripts > Open Scripts Folder, put the script there, Rescan, run it). It adds the
   slices (with nine-patch centres) and saves \`ui.aseprite\` beside the template. \`ui-template-guide.png\` is a map: each piece numbered, with a legend of names, sizes and nine-patch insets.
2. **Draw.** Work inside the slices. A slice with a nine-patch centre (Slice properties > "Is 9-slice") stretches: the corners and edges stay as drawn, the centre grows - so the
   frame is a small source (a corner, a strip of edge, a flat middle), not a full-size example. Move the centre to change how much of each edge is kept; resize a slice if the piece
   needs more room (leave a gap to its neighbours). The game draws the pieces at whatever size a widget needs, so only the look matters here.
3. **Slice.** \`node packages/ui/tools/slice-sheet.mjs --aseprite="C:/path/to/Aseprite.exe" packages/ui/art/ui.aseprite\` exports the slices with Aseprite's command line and writes
   \`assets/ui/sprites/ui/<name>.png\` and \`assets/ui/data/frames.json\` (each frame's size and nine-patch insets). Frames you delete from the sprite are removed from the atlas.
   (Or export from Aseprite yourself - File > Export Sprite Sheet, "JSON Data" and "Meta: Slices" ticked - and give the tool the PNG and JSON: \`slice-sheet.mjs sheet.png sheet.json\`.)
4. **See it.** The dev server picks the new frames up; the gallery (\`#ui\` on the page address) shows them all.

New frames: add a slice named in lowercase letters, digits and underscores (never ending in \`_f\` and a number); the skin (\`assets/ui/data/skin.json\`) says which widget uses it.
`);

console.log(`${placed.length} pieces on a ${SHEET_WIDTH}x${height} sheet -> ${artDir}`);
console.log("  ui-template.png, ui-template.lua, ui-template-guide.png, README.md");
